# results/email_service.py

import base64

import resend
from django.conf import settings


def send_result_email(
    *,
    recipient_email: str,
    student_name: str,
    term_name: str,
    session_name: str,
    pdf_bytes: bytes,
    pdf_filename: str,
) -> dict:
    """
    Send a student's result PDF to a parent using Resend.

    The PDF is generated by the frontend and passed here as bytes.
    Django does not generate or store the PDF.
    """

    if not recipient_email:
        raise ValueError("Parent email address is not available.")

    if not settings.RESEND_API_KEY:
        raise ValueError("RESEND_API_KEY is not configured.")

    resend.api_key = settings.RESEND_API_KEY

    pdf_base64 = base64.b64encode(pdf_bytes).decode("utf-8")

    subject = f"{student_name} - {term_name} Result"

    html = f"""
    <p>Dear Parent/Guardian,</p>

    <p>
        Please find attached the academic result for
        <strong>{student_name}</strong> for
        <strong>{term_name}</strong>,
        <strong>{session_name}</strong>.
    </p>

    <p>
        Kindly find the student's result attached to this email.
    </p>

    <p>
        Regards,<br>
        <strong>{settings.RESEND_FROM_NAME}</strong>
    </p>
    """

    response = resend.Emails.send(
        {
            "from": (
                f"{settings.RESEND_FROM_NAME} "
                f"<{settings.RESEND_FROM_EMAIL}>"
            ),
            "to": [recipient_email],
            "subject": subject,
            "html": html,
            "attachments": [
                {
                    "filename": pdf_filename,
                    "content": pdf_base64,
                }
            ],
        }
    )

    return response